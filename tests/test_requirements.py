"""The locked dependencies: requirements.in and requirements-clock.in say what the project needs, the matching .txt
files (made by pip-compile) pin every package to an exact version with hashes, and every workflow installs with
--require-hashes. A new release can then never reach a deploy without a pull request changing the lock.

Everything here reads files in the repo; nothing touches the network or the installed packages."""

import re
from pathlib import Path

import pytest
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parent.parent
PAIRS = [("requirements.in", "requirements.txt"), ("requirements-clock.in", "requirements-clock.txt")]
WORKFLOWS = sorted((ROOT / ".github" / "workflows").glob("*.yml"))


def read(name):
    return (ROOT / name).read_text(encoding="utf-8")


def wanted(name):
    """[Requirement] from a .in file, ignoring comments and blank lines."""
    return [Requirement(line.strip()) for line in read(name).splitlines() if line.strip() and not line.lstrip().startswith("#")]


def locked(name):
    """{canonical name: (version, [sha256 hashes])} from a pip-compile file."""
    out, cur = {}, None
    for line in read(name).splitlines():
        m = re.match(r"^([A-Za-z0-9_.-]+)==([^\s;\\]+)", line)
        if m:
            cur = canonicalize_name(m.group(1))
            assert cur not in out, f"{cur} is pinned twice in {name}"
            out[cur] = (m.group(2), [])
        out_hashes = re.findall(r"--hash=sha256:([0-9a-f]{64})", line)
        if out_hashes:
            assert cur, f"a hash before any package in {name}"
            out[cur][1].extend(out_hashes)
    return out


@pytest.mark.parametrize("source, lock", PAIRS)
def test_every_package_is_pinned_exactly_and_has_hashes(source, lock):
    pins = locked(lock)
    assert pins, lock
    for name, (version, hashes) in pins.items():
        assert re.fullmatch(r"\d+(\.\d+)*", version), (name, version)           # an exact release, no ranges or pre-releases
        assert hashes and len(hashes) == len(set(hashes)), name                 # at least one hash, none repeated
    # no unpinned or loose line slipped in beside the pinned ones
    for line in read(lock).splitlines():
        if line.strip() and not line.startswith((" ", "#")):
            assert re.match(r"^[A-Za-z0-9_.-]+==[^\s;\\]+ \\$", line), f"{lock}: {line!r}"


@pytest.mark.parametrize("source, lock", PAIRS)
def test_every_direct_requirement_is_in_the_lock_at_a_version_it_accepts(source, lock):
    pins = locked(lock)
    for req in wanted(source):
        name = canonicalize_name(req.name)
        assert name in pins, f"{req.name} is in {source} but not in {lock}"
        assert req.specifier.contains(pins[name][0], prereleases=False), (req, pins[name][0])


def test_pillow_is_pinned_exactly_in_both_places():
    """Pillow draws the preview images; a different version could change their bytes."""
    (req,) = [r for r in wanted("requirements.in") if canonicalize_name(r.name) == "pillow"]
    (spec,) = list(req.specifier)
    assert spec.operator == "==" and locked("requirements.txt")["pillow"][0] == spec.version


def test_the_lock_headers_name_the_command_and_the_python_the_workflows_use():
    versions = set()
    for source, lock in PAIRS:
        head = "\n".join(line for line in read(lock).splitlines() if line.startswith("#"))
        assert f"pip-compile --generate-hashes {source}" in head, lock
        versions.add(re.search(r"autogenerated by pip-compile with Python (\d+\.\d+)", head).group(1))
    assert len(versions) == 1
    for flow in WORKFLOWS:
        for found in re.findall(r'python-version:\s*"?(\d+\.\d+)"?', flow.read_text(encoding="utf-8")):
            assert found == versions.copy().pop(), f"{flow.name} installs on Python {found}, the lock was made with {versions}"


def test_every_workflow_installs_python_packages_only_from_the_lock_with_hashes_required():
    installs = 0
    for flow in WORKFLOWS:
        for line in flow.read_text(encoding="utf-8").splitlines():
            if re.search(r"\bpip install\b", line):
                installs += 1
                assert "--require-hashes" in line, f"{flow.name}: {line.strip()}"
                assert re.search(r"-r requirements(-clock)?\.txt", line) and ".in" not in line, f"{flow.name}: {line.strip()}"
    assert installs >= 4                                                          # checks (two), the update build and the snapshot


def test_dependabot_watches_pip_as_well_as_actions():
    text = read(".github/dependabot.yml")
    assert "package-ecosystem: pip" in text and "package-ecosystem: github-actions" in text
